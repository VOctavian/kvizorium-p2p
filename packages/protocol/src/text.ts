const TEXTS: Record<Lang, Record<TextKey, Fmt>> = { ru, en };

export const text = (key: TextKey, params?: TextParams): Text => (params ? { key, params } : { key });

/** Renders a server text in a language. Unknown keys (a newer server) fall back to an empty string. */
export function formatText(lang: Lang, t: Text | string): string {
  if (typeof t === "string") return t;
  const f = TEXTS[lang][t.key] ?? TEXTS.ru[t.key];
  return f ? f(t.params ?? {}) : "";
}
