/**
 * Texts the server generates (feed events, host lines, errors), as message keys with params.
 * The server sends `{ key, params }`; every client renders it in its own language.
 * The server also renders Russian into the old plain-text fields, for bots and logs.
 */

export type Lang = "ru" | "en";
export type TextParams = Record<string, string | number | undefined>;
export interface Text { key: TextKey; params?: TextParams }

type Fmt = (p: TextParams) => string;

/** Russian plural: 1 раунд, 2 раунда, 5 раундов. */
export function pluralRu(n: number, one: string, few: string, many: string) {
  const m10 = n % 10, m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
}
export const pluralEn = (n: number, one: string, many: string) => (n === 1 ? one : many);

