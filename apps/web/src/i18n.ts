const DICTS: Record<Lang, Dict> = { ru, en };

export interface T extends Dict {
  lang: Lang;
  /** Renders a server text (feed event, host line, error) in the current language. */
  tx: (t: Text | string | undefined) => string;
}

const cache = new Map<Lang, T>();
function forLang(lang: Lang): T {
  let t = cache.get(lang);
  if (!t) {
    t = { ...(DICTS[lang] ?? ru), lang, tx: (x) => (x == null ? "" : formatText(lang, x)) };
    cache.set(lang, t);
  }
  return t;
}

/** Texts in the language picked in settings; components re-render when it changes. */
export function useT(): T { return forLang(usePrefs().lang); }
/** The same outside components (toasts, network errors). */
export function tr(): T { return forLang(getPrefs().lang); }

